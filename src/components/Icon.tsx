/** Initialen-Logo mit stabiler Farbe pro Anbieter (keine fremden Marken-Logos). */
export function Avatar({ name, size }: { name: string; size?: 'lg' }) {
  const clean = name.replace(/[^\p{L}\p{N} ]/gu, '').trim();
  const parts = clean.split(/\s+/).filter(Boolean);
  const initials = (parts.length > 1 ? parts[0][0] + parts[1][0] : clean.slice(0, 2)).toUpperCase() || '?';
  let hash = 0;
  for (const ch of name.toLowerCase()) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return (
    <span className={`avatar av-${hash % 6} ${size ?? ''}`} aria-hidden="true">
      {initials}
    </span>
  );
}
